// Lark のテキストメッセージは `<at user_id="all">所有人</at>`（全員メンション）などをタグとして解釈する。
// 通知文には応募フォームの入力値（氏名・UTM など）をそのまま入れているため、外部から POST された値で
// 社内チャットに全員メンションを差し込めてしまう。自前の文面ではタグを使っていないので、送信の直前に
// < > を全角へ置き換える。全角化は何度かけても結果が変わらないので、送信経路が重なっても安全。
export const neutralizeLarkTags = (text: string): string => text.replace(/</g, '＜').replace(/>/g, '＞');
